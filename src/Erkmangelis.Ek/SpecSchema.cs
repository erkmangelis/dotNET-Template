using System.Text.Json;
using System.Text.Json.Nodes;

namespace Erkmangelis.Ek;

/// <summary>
/// Builds the JSON Schema of a project spec from the catalog, so the schema never lists an option
/// or value the template does not have. The checked-in schemas/ek-spec.schema.json must match it.
/// </summary>
public static class SpecSchema
{
    public const string Id = "https://github.com/erkmangelis/dotNET-Template/blob/main/schemas/ek-spec.schema.json";

    public static string Generate(Catalog catalog)
    {
        var options = new JsonObject();
        foreach (var option in catalog.Options)
        {
            options[option.Name] = option.IsBool
                ? new JsonObject { ["description"] = option.Description, ["type"] = "boolean", ["default"] = option.Default == "true" }
                : new JsonObject
                {
                    ["description"] = option.Description,
                    ["enum"] = new JsonArray([.. option.Choices.Select(choice => (JsonNode)choice.Value)]),
                    ["default"] = option.Default,
                };
        }

        var presets = catalog.Presets.SelectMany(preset => preset.Aliases.Prepend(preset.Name)).Select(name => (JsonNode)name);
        var schema = new JsonObject
        {
            ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
            ["$id"] = Id,
            ["title"] = $"{catalog.Template.ShortName} project spec",
            ["description"] = "A request to generate a project, and the provenance (template-origin.json) of a generated one. Generated by `ek schema` from catalog/.",
            ["type"] = "object",
            ["additionalProperties"] = false,
            ["properties"] = new JsonObject
            {
                ["$schema"] = new JsonObject { ["type"] = "string" },
                ["specVersion"] = new JsonObject { ["description"] = "The spec format version.", ["const"] = ProjectSpec.CurrentVersion },
                ["template"] = new JsonObject
                {
                    ["description"] = "The template, by identity or short name.",
                    ["enum"] = new JsonArray(catalog.Template.Identity, catalog.Template.ShortName),
                },
                ["package"] = new JsonObject { ["description"] = "The template package.", ["const"] = catalog.Template.Package },
                ["version"] = new JsonObject { ["description"] = "The template package version that generated, or should generate, the project.", ["type"] = "string" },
                ["name"] = new JsonObject
                {
                    ["description"] = "The project name, used for namespaces, project files and the solution.",
                    ["type"] = "string",
                    ["pattern"] = "^[A-Za-z][A-Za-z0-9_]*(\\.[A-Za-z][A-Za-z0-9_]*)*$",
                },
                ["preset"] = new JsonObject
                {
                    ["description"] = "A named starting point. Options given next to it win over its values.",
                    ["enum"] = new JsonArray([.. presets]),
                },
                ["options"] = new JsonObject
                {
                    ["description"] = "Template options. An option left out takes the value a rule needs, or its default.",
                    ["type"] = "object",
                    ["additionalProperties"] = false,
                    ["properties"] = options,
                },
            },
        };
        return schema.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";
    }
}
